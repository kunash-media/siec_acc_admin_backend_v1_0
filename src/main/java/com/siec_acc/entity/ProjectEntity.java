package com.siec_acc.entity;



import jakarta.persistence.*;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

@Entity
@Table(name = "projects", indexes = {
        @Index(name = "idx_projects_status", columnList = "project_status"),
        @Index(name = "idx_projects_client", columnList = "client_str_id")
})
public class ProjectEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "project_prime_id")
    private Long projectPrimeId;

    // Generated right after the first save (needs the DB id) - same pattern as PurchaseBillEntity.
    @Column(name = "project_str_id", unique = true, length = 30)
    private String projectStrId;

    // Auto-generated by the server (e.g. 26LW073), never taken from the client.
    @Column(name = "project_code", nullable = false, unique = true, length = 40)
    private String projectCode;

    @Column(name = "project_name", nullable = false)
    private String projectName;

    // Soft link to ClientEntity.clientStrId + name snapshot (same convention as other modules).
    @Column(name = "client_str_id", length = 30)
    private String clientStrId;

    @Column(name = "project_customer_name", nullable = false)
    private String customerName;

    @Column(name = "project_manager")
    private String projectManager;

    // active | pending | onhold | completed | cancelled
    @Column(name = "project_status", nullable = false, length = 20)
    private String status = "active";

    @Column(name = "start_date")
    private LocalDate startDate;

    @Column(name = "end_date")
    private LocalDate endDate;

    @Column(name = "progress")
    private Integer progress = 0;

    @Column(name = "total_budget", precision = 15, scale = 2)
    private BigDecimal totalBudget = BigDecimal.ZERO;

    @Column(name = "purchase_budget", precision = 15, scale = 2)
    private BigDecimal purchaseBudget = BigDecimal.ZERO;

    @Column(name = "expense_budget", precision = 15, scale = 2)
    private BigDecimal expenseBudget = BigDecimal.ZERO;

    @Column(name = "hours_budget", precision = 15, scale = 2)
    private BigDecimal hoursBudget = BigDecimal.ZERO;

    @Column(name = "project_description", columnDefinition = "TEXT")
    private String description;

    @Column(name = "hold_reason", length = 1000)
    private String holdReason;

    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() { this.createdAt = LocalDateTime.now(); this.updatedAt = LocalDateTime.now(); }

    @PreUpdate
    protected void onUpdate() { this.updatedAt = LocalDateTime.now(); }

    public ProjectEntity() {}

    public Long getProjectPrimeId() {
        return projectPrimeId;
    }

    public void setProjectPrimeId(Long projectPrimeId) {
        this.projectPrimeId = projectPrimeId;
    }

    public String getProjectStrId() {
        return projectStrId;
    }

    public void setProjectStrId(String projectStrId) {
        this.projectStrId = projectStrId;
    }

    public String getProjectCode() {
        return projectCode;
    }

    public void setProjectCode(String projectCode) {
        this.projectCode = projectCode;
    }

    public String getProjectName() {
        return projectName;
    }

    public void setProjectName(String projectName) {
        this.projectName = projectName;
    }

    public String getClientStrId() {
        return clientStrId;
    }

    public void setClientStrId(String clientStrId) {
        this.clientStrId = clientStrId;
    }

    public String getCustomerName() {
        return customerName;
    }

    public void setCustomerName(String customerName) {
        this.customerName = customerName;
    }

    public String getProjectManager() {
        return projectManager;
    }

    public void setProjectManager(String projectManager) {
        this.projectManager = projectManager;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public void setStartDate(LocalDate startDate) {
        this.startDate = startDate;
    }

    public LocalDate getEndDate() {
        return endDate;
    }

    public void setEndDate(LocalDate endDate) {
        this.endDate = endDate;
    }

    public Integer getProgress() {
        return progress;
    }

    public void setProgress(Integer progress) {
        this.progress = progress;
    }

    public BigDecimal getTotalBudget() {
        return totalBudget;
    }

    public void setTotalBudget(BigDecimal totalBudget) {
        this.totalBudget = totalBudget;
    }

    public BigDecimal getPurchaseBudget() {
        return purchaseBudget;
    }

    public void setPurchaseBudget(BigDecimal purchaseBudget) {
        this.purchaseBudget = purchaseBudget;
    }

    public BigDecimal getExpenseBudget() {
        return expenseBudget;
    }

    public void setExpenseBudget(BigDecimal expenseBudget) {
        this.expenseBudget = expenseBudget;
    }

    public BigDecimal getHoursBudget() {
        return hoursBudget;
    }

    public void setHoursBudget(BigDecimal hoursBudget) {
        this.hoursBudget = hoursBudget;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getHoldReason() {
        return holdReason;
    }

    public void setHoldReason(String holdReason) {
        this.holdReason = holdReason;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}